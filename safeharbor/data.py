def generate_notes(n: int = 300, seed: int = 7) -> list[dict]:
    rng = random.Random(seed)
    notes = []
    for i in range(n):
        first, last = rng.choice(_FIRST), rng.choice(_LAST)
        cond, med, finding = rng.choice(_CONDITIONS)
        cond2 = rng.choice(_CONDITIONS)
        dob = date(1940, 1, 1) + timedelta(days=rng.randint(0, 365 * 60))
        visit = date(2026, 1, 1) + timedelta(days=rng.randint(0, 300))
        mrn = f"{rng.randint(10**7, 10**8 - 1)}"
        phone = f"({rng.randint(200, 989)}) {rng.randint(200, 999)}-{rng.randint(1000, 9999)}"
        addr = f"{rng.randint(10, 9999)} {rng.choice(_STREETS)}"
        zipc = f"{rng.randint(10000, 99999)}"
        relative = rng.choice(_FIRST)
        kind = rng.choice(["Progress note", "Discharge summary", "Clinic visit"])
        text = (
            f"{kind}. Patient: {first} {last}. DOB: {dob:%m/%d/%Y}. MRN: {mrn}. "
            f"Address: {addr}, Springfield {zipc}. Phone: {phone}. "
            f"Visit date {visit.isoformat()}. "
            f"{first} is a {2026 - dob.year}-year-old with a history of {cond} and {cond2[0]}. "
            f"Current medications include {med} and {cond2[1]}. "
            f"On examination: {finding}; {cond2[2]}. "
            f"Assessment: {cond}, suboptimally controlled. {rng.choice(_PLANS)} "
            f"Emergency contact: {relative} {last}, {phone}."
        )
        notes.append({
            "doc_id": f"note-{i:04d}",
            "topic": cond,
            "section": kind.lower(),
            "source": "synthetic-ehr",
            "collection": "patient_notes",
            "text": text,
            "_known_names": [f"{first} {last}", f"{relative} {last}"],
        })
    return notes
