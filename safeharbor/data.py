"""Data sources.

1. **Public medical knowledge** - MedQuAD (Ben Abacha & Demner-Fushman, 2019, CC BY 4.0):
   16,407 question/answer pairs curated from 12 NIH websites (MedlinePlus, GARD, GHR, NIDDK,
   NCI, ...). We normalise each answer into a document with ``topic`` (disease / drug name),
   ``section`` (the NIH question type: symptoms, treatment, inheritance, ...), and ``source``.

2. **Private clinical notes** - synthetic discharge / progress notes generated by
   ``generate_notes()`` with realistic PHI (names, DOB, MRN, phone, address). They stand in for
   real EHR exports, which by definition we cannot publish. They exercise the PHI-redaction path.
"""
from __future__ import annotations

import hashlib
import json
import random
import re
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

MEDQUAD_HF = "keivalya/MedQuad-MedicalQnADataset"

# question template -> regex capturing the topic
_TOPIC_PATTERNS = [
    r"^what (?:is|are) \(are\) (.+?)\s*\??$",
    r"^what (?:is|are) the symptoms of (.+?)\s*\??$",
    r"^what are the signs and symptoms of (.+?)\s*\??$",
    r"^what are the treatments? for (.+?)\s*\??$",
    r"^what are the genetic changes related to (.+?)\s*\??$",
    r"^what causes (.+?)\s*\??$",
    r"^what (?:is|are) the outlook for (.+?)\s*\??$",
    r"^what (?:is|are) the stages of (.+?)\s*\??$",
    r"^what (?:is|are) the complications of (.+?)\s*\??$",
    r"^what research \(or clinical trials\) is being done for (.+?)\s*\??$",
    r"^what to do for (.+?)\s*\??$",
    r"^what (?:is|are) (.+?)\s*\??$",
    r"^who is at risk for (.+?)\s*\??$",
    r"^how to diagnose (.+?)\s*\??$",
    r"^how to prevent (.+?)\s*\??$",
    r"^how many people are affected by (.+?)\s*\??$",
    r"^is (.+?) inherited\s*\??$",
    r"^do you have information about (.+?)\s*\??$",
    r"^(?:what are )?the (?:symptoms|treatments?) (?:of|for) (.+?)\s*\??$",
]
_TOPIC_RES = [re.compile(p, re.I) for p in _TOPIC_PATTERNS]


def normalise_question(q: str) -> str:
    q = re.sub(r"\s+", " ", q).strip()
    q = re.sub(r"\s*\?\s*\?$", " ?", q)
    return q


def extract_topic(question: str) -> str:
    q = normalise_question(question).rstrip(" ?")
    for rx in _TOPIC_RES:
        m = rx.match(q + " ?") or rx.match(q)
        if m:
            t = m.group(1).strip(" ?")
            if 2 < len(t) < 120:
                return t
    return q[:120]


def _doc_id(text: str) -> str:
    return "mq-" + hashlib.sha1(text.encode()).hexdigest()[:12]


def load_medquad(raw_dir: str | Path, refresh: bool = False) -> tuple[list[dict], list[dict]]:
    """Return (documents, qa_pairs).

    * documents: unique answers (exact duplicates merged), each with topic/section metadata.
    * qa_pairs:  {question, gold_doc_ids, section} - every doc that answers the same normalised
      question counts as relevant (MedQuAD has the same question answered by several NIH sites).
    """
    raw_dir = Path(raw_dir)
    snap = raw_dir / "medquad.jsonl"
    if not snap.exists() or refresh:
        from datasets import load_dataset

        ds = load_dataset(MEDQUAD_HF, split="train")
        raw_dir.mkdir(parents=True, exist_ok=True)
        with snap.open("w") as f:
            for r in ds:
                f.write(json.dumps({"qtype": r["qtype"], "question": r["Question"], "answer": r["Answer"]}) + "\n")

    docs: dict[str, dict] = {}
    q_to_docs: dict[str, set] = defaultdict(set)
    q_section: dict[str, str] = {}
    with snap.open() as f:
        for line in f:
            r = json.loads(line)
            ans = re.sub(r"\s+", " ", (r["answer"] or "")).strip()
            if len(ans) < 40:
                continue
            did = _doc_id(ans)
            q = normalise_question(r["question"])
            if did not in docs:
                docs[did] = {
                    "doc_id": did,
                    "topic": extract_topic(q),
                    "section": r["qtype"],
                    "source": "MedQuAD/NIH",
                    "collection": "medical_kb",
                    "text": ans,
                }
            q_to_docs[q.lower()].add(did)
            q_section[q.lower()] = r["qtype"]

    qa = [
        {"question": q, "gold_doc_ids": sorted(ids), "section": q_section[q]}
        for q, ids in q_to_docs.items()
    ]
    return list(docs.values()), qa


